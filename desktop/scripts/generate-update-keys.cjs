#!/usr/bin/env node
/**
 * 生成桌面端自动更新签名密钥对。
 *
 * 私钥写入 .secrets/update-private.pem（切勿提交）。
 * 公钥以 TypeScript 常量形式写入 desktop/electron/updatePublicKey.ts，
 * 供 updater.ts 在本地校验更新包签名时使用。
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const PRIVATE_KEY_PATH = path.join(REPO_ROOT, '.secrets', 'update-private.pem');
const PUBLIC_KEY_TS_PATH = path.join(__dirname, '..', 'electron', 'updatePublicKey.ts');

function main() {
  if (fs.existsSync(PRIVATE_KEY_PATH)) {
    console.error(`Private key already exists at ${PRIVATE_KEY_PATH}. Delete it first to regenerate.`);
    process.exit(1);
  }

  const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 4096,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });

  fs.mkdirSync(path.dirname(PRIVATE_KEY_PATH), { recursive: true });
  fs.writeFileSync(PRIVATE_KEY_PATH, privateKey);
  fs.chmodSync(PRIVATE_KEY_PATH, 0o600);

  const escapedKey = JSON.stringify(publicKey);
  const tsContent = `// Auto-generated by scripts/generate-update-keys.js
// Do not edit manually. This is the public key used to verify desktop update packages.

export const UPDATE_PUBLIC_KEY = ${escapedKey};
`;
  fs.writeFileSync(PUBLIC_KEY_TS_PATH, tsContent);

  console.log(`Private key saved to: ${PRIVATE_KEY_PATH}`);
  console.log(`Public key constant saved to: ${PUBLIC_KEY_TS_PATH}`);
}

main();
